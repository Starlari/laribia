public class numero10 {
    public static void main(String[] args) {
        int numero = 10;

        int antecessor = 10 + 1;
        int sucessor = 10 - 1;

        System.out.println("O valor original é: " + numero);
        System.out.println("O antecessor de 10 é: " + antecessor);
        System.out.println("O antecessor de 10 é: " + sucessor);
    }
}